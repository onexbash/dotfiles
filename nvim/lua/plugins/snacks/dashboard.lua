local stats

local function startup()
	if not stats then
		local plugins = vim.pack.get()
		local active = #vim.tbl_filter(function(p)
			return p.active
		end, plugins)
		stats = {
			active = active,
			total = #plugins,
			ms = (vim.uv.hrtime() - _G.nvim_start) / 1e6,
		}
	end
	return {
		align = "center",
		text = {
			{ "⚡ Neovim loaded ", hl = "footer" },
			{ stats.active .. "/" .. stats.total, hl = "special" },
			{ " plugins in ", hl = "footer" },
			{ string.format("%.2fms", stats.ms), hl = "special" },
		},
	}
end

